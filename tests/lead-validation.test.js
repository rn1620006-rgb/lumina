'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {validate}=require('../lib/lead-validation');
const valid={kind:'cliente',fullName:'Maria Silva',email:'Maria@EXAMPLE.pt',city:'Quarteira',privacyConsent:true};
test('aceita interesse válido e normaliza email',()=>{const r=validate(valid);assert.equal(r.ok,true);assert.equal(r.data.email,'maria@example.pt');});
test('rejeita pedido sem consentimento',()=>{assert.equal(validate({...valid,privacyConsent:false}).ok,false);});
test('rejeita papel desconhecido',()=>{assert.equal(validate({...valid,kind:'admin'}).ok,false);});
test('rejeita email inválido',()=>{assert.equal(validate({...valid,email:'email-invalido'}).ok,false);});
test('rejeita mensagem excessiva',()=>{assert.equal(validate({...valid,message:'x'.repeat(751)}).ok,false);});
test('rejeita honeypot preenchido',()=>{assert.equal(validate({...valid,website:'bot.test'}).ok,false);});
